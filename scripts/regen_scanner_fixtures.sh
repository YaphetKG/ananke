#!/usr/bin/env bash
# Regenerate tests/fixtures/scanner_output/ from REAL scanner runs.
#
# Run this on a machine that has trivy, osv-scanner, gitleaks, uv and npm on PATH
# (the Ananke dev host does not). It never modifies the committed fixture repos:
# everything is copied to a temp dir first, and results are staged and only moved
# into tests/fixtures/scanner_output/ once every scan has succeeded.
#
# Fix targets can be overridden from the environment, e.g.
#   PY_REQUESTS_FIX=2.33.0 PY_URLLIB3_FIX=2.8.0 JS_LODASH_FIX=4.18.0 scripts/regen_scanner_fixtures.sh
# NOTE: with the defaults below (the versions the unit tests and fake-model script use),
# real scanners WILL still report some newer advisories in the after_* files, e.g.
# requests CVE-2024-47081 (fixed 2.32.4) and urllib3 CVE-2025-50181 (fixed 2.5.0). See README.md.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
ROOT="$(cd "${SCRIPT_DIR}/.." && pwd -P)"
FIXTURES="${ROOT}/tests/fixtures"
REPOS="${FIXTURES}/repos"
OUT="${FIXTURES}/scanner_output"

PY_REQUESTS_FIX="${PY_REQUESTS_FIX:-2.32.3}"
PY_URLLIB3_FIX="${PY_URLLIB3_FIX:-2.2.3}"
JS_LODASH_FIX="${JS_LODASH_FIX:-4.17.21}"
# Path prefix that replaces the temp dir in recorded output, so fixtures are stable.
SCAN_PREFIX="/scan"

die() { echo "regen_scanner_fixtures: $*" >&2; exit 1; }
log() { echo "==> $*" >&2; }

# ---------------------------------------------------------------- preflight
missing=()
for bin in trivy osv-scanner gitleaks uv npm; do
    command -v "${bin}" >/dev/null 2>&1 || missing+=("${bin}")
done
if ((${#missing[@]})); then
    die "missing required binaries: ${missing[*]}
Install them (official release builds) and re-run. Nothing was changed."
fi
[[ -f "${REPOS}/py-vulnerable/pyproject.toml" ]] || die "fixture repo not found: ${REPOS}/py-vulnerable"
[[ -f "${REPOS}/js-vulnerable/package.json" ]] || die "fixture repo not found: ${REPOS}/js-vulnerable"

WORK="$(mktemp -d "${TMPDIR:-/tmp}/ananke-regen.XXXXXX")"
WORK="$(cd "${WORK}" && pwd -P)"
trap 'rm -rf "${WORK}"' EXIT
STAGE="${WORK}/stage"
mkdir -p "${STAGE}/trivy" "${STAGE}/osv" "${STAGE}/gitleaks"

# Replace the temp dir with SCAN_PREFIX in a recorded JSON file.
normalize() {
    local f="$1"
    sed -e "s|${WORK}/src|${SCAN_PREFIX}|g" -e "s|${WORK}|${SCAN_PREFIX}|g" "${f}" >"${f}.tmp"
    mv "${f}.tmp" "${f}"
}

# ---------------------------------------------------------------- versions
log "recording tool versions"
{
    echo "# Scanner versions used to generate these fixtures"
    echo
    echo "Generated by \`scripts/regen_scanner_fixtures.sh\` on $(date -u +%Y-%m-%dT%H:%M:%SZ) ($(uname -sm))."
    echo
    for cmd in "trivy --version" "osv-scanner --version" "gitleaks version" "uv --version" "npm --version"; do
        echo "## \`${cmd}\`"
        echo
        echo '```'
        ${cmd} 2>&1
        echo '```'
        echo
    done
    echo "Fix targets: requests==${PY_REQUESTS_FIX}, urllib3==${PY_URLLIB3_FIX}, lodash ${JS_LODASH_FIX}."
} >"${STAGE}/VERSIONS.md"

# ---------------------------------------------------------------- scanners
run_trivy() { # <dir> <out>
    (cd "$1" && trivy fs --scanners vuln,misconfig,secret --format json --ignore-unfixed \
        --quiet --output "$2" .)
    normalize "$2"
}

run_osv() { # <lockfile> <out>
    local rc=0
    osv-scanner scan --format json --lockfile "$1" >"$2" || rc=$?
    # 0 = no vulnerabilities, 1 = vulnerabilities found; anything else is a real error.
    if [[ ${rc} -ne 0 && ${rc} -ne 1 ]]; then
        die "osv-scanner failed (exit ${rc}) on $1"
    fi
    normalize "$2"
}

run_gitleaks() { # <dir> <out> <config>
    (cd "$1" && gitleaks dir --no-banner --config "$3" --report-format json \
        --report-path "$2" --exit-code 0 .)
    normalize "$2"
}

# The copies live at ${WORK}/src/<name> so that normalized paths read /scan/<name>/...
mkdir -p "${WORK}/src"

# ---- Python fixture
PY="${WORK}/src/py-vulnerable"
cp -R "${REPOS}/py-vulnerable" "${PY}"
rm -rf "${PY}/.venv"
log "py-vulnerable: before"
run_trivy "${PY}" "${STAGE}/trivy/before_py.json"
run_osv "${PY}/uv.lock" "${STAGE}/osv/before_py.json"

log "py-vulnerable: applying fix (requests==${PY_REQUESTS_FIX}, urllib3==${PY_URLLIB3_FIX})"
sed -e "s/\"requests==[^\"]*\"/\"requests==${PY_REQUESTS_FIX}\"/" \
    -e "s/\"urllib3==[^\"]*\"/\"urllib3==${PY_URLLIB3_FIX}\"/" \
    "${PY}/pyproject.toml" >"${PY}/pyproject.toml.new"
mv "${PY}/pyproject.toml.new" "${PY}/pyproject.toml"
grep -q "requests==${PY_REQUESTS_FIX}" "${PY}/pyproject.toml" || die "failed to bump requests pin"
grep -q "urllib3==${PY_URLLIB3_FIX}" "${PY}/pyproject.toml" || die "failed to bump urllib3 pin"
(cd "${PY}" && uv lock)
log "py-vulnerable: after"
run_trivy "${PY}" "${STAGE}/trivy/after_py.json"
run_osv "${PY}/uv.lock" "${STAGE}/osv/after_py.json"

# ---- JavaScript fixture
JS="${WORK}/src/js-vulnerable"
cp -R "${REPOS}/js-vulnerable" "${JS}"
rm -rf "${JS}/node_modules"
log "js-vulnerable: before"
run_trivy "${JS}" "${STAGE}/trivy/before_js.json"
run_osv "${JS}/package-lock.json" "${STAGE}/osv/before_js.json"

log "js-vulnerable: applying fix (lodash ${JS_LODASH_FIX})"
sed -e "s/\"lodash\": *\"[^\"]*\"/\"lodash\": \"${JS_LODASH_FIX}\"/" \
    "${JS}/package.json" >"${JS}/package.json.new"
mv "${JS}/package.json.new" "${JS}/package.json"
grep -q "\"lodash\": \"${JS_LODASH_FIX}\"" "${JS}/package.json" || die "failed to bump lodash"
(cd "${JS}" && npm install --package-lock-only --ignore-scripts --no-audit --no-fund)
rm -rf "${JS}/node_modules"
log "js-vulnerable: after"
run_trivy "${JS}" "${STAGE}/trivy/after_js.json"
run_osv "${JS}/package-lock.json" "${STAGE}/osv/after_js.json"

# ---- gitleaks
# gitleaks' default config allowlists AWS keys ending in "EXAMPLE" (rule aws-access-token,
# allowlist regex '.+EXAMPLE$'), so the documentation key would never be reported. Use a
# minimal config with the same rule id/regex/entropy but no allowlist.
GL_CONFIG="${WORK}/gitleaks.toml"
cat >"${GL_CONFIG}" <<'TOML'
title = "ananke fixture config: default aws-access-token rule without the EXAMPLE allowlist"

[[rules]]
id = "aws-access-token"
description = "Identified a pattern that may indicate AWS credentials, risking unauthorized cloud resource access and data breaches on AWS platforms."
regex = '''\b((?:A3T[A-Z0-9]|AKIA|ASIA|ABIA|ACCA)[A-Z2-7]{16})\b'''
entropy = 3
keywords = ["a3t", "akia", "asia", "abia", "acca"]
TOML

GL_SECRET="${WORK}/src/gitleaks-secret"
GL_CLEAN="${WORK}/src/gitleaks-clean"
mkdir -p "${GL_SECRET}" "${GL_CLEAN}"
# AKIAIOSFODNN7EXAMPLE is the AWS documentation example access key id; it is not a credential.
printf '# Ananke gitleaks fixture: AWS documentation example key, not a real credential.\nAWS_ACCESS_KEY_ID=AKIAIOSFODNN7EXAMPLE\n' \
    >"${GL_SECRET}/settings.env"
printf 'Nothing secret here.\n' >"${GL_CLEAN}/README.txt"
log "gitleaks"
run_gitleaks "${GL_SECRET}" "${STAGE}/gitleaks/one_secret.json" "${GL_CONFIG}"
run_gitleaks "${GL_CLEAN}" "${STAGE}/gitleaks/clean.json" "${GL_CONFIG}"
grep -q 'AKIAIOSFODNN7EXAMPLE' "${STAGE}/gitleaks/one_secret.json" \
    || die "gitleaks did not report the example key; check ${GL_CONFIG}"

# ---------------------------------------------------------------- README
cat >"${STAGE}/README.md" <<EOF
# Scanner output fixtures

**Every JSON file in this directory is real tool output**, generated by
\`scripts/regen_scanner_fixtures.sh\` on $(date -u +%Y-%m-%d). Exact tool and
vulnerability-DB versions are recorded in [VERSIONS.md](VERSIONS.md).

| File | Command (run inside a temp copy of the fixture repo) |
|---|---|
| \`trivy/before_py.json\`, \`trivy/after_py.json\` | \`trivy fs --scanners vuln,misconfig,secret --format json --ignore-unfixed .\` in \`repos/py-vulnerable\` |
| \`trivy/before_js.json\`, \`trivy/after_js.json\` | same, in \`repos/js-vulnerable\` |
| \`osv/before_*.json\`, \`osv/after_*.json\` | \`osv-scanner scan --format json --lockfile <uv.lock or package-lock.json>\` |
| \`gitleaks/one_secret.json\` | \`gitleaks dir --report-format json\` on a scratch dir holding \`settings.env\` with \`AKIAIOSFODNN7EXAMPLE\` |
| \`gitleaks/clean.json\` | same, on a scratch dir with no secrets |

- \`before_*\` = the committed fixture repo as-is. \`after_*\` = after bumping
  requests==${PY_REQUESTS_FIX}, urllib3==${PY_URLLIB3_FIX} (then \`uv lock\`) or
  lodash ${JS_LODASH_FIX} (then \`npm install --package-lock-only --ignore-scripts\`).
- The temp directory prefix in recorded paths is rewritten to \`${SCAN_PREFIX}\` so the files are stable.
- gitleaks runs with a minimal config containing only the upstream \`aws-access-token\` rule
  **without** its \`.+EXAMPLE\$\` allowlist; the default config deliberately ignores the AWS
  documentation key. \`AKIAIOSFODNN7EXAMPLE\` is not a real credential.
- The after_* files can still contain advisories that the chosen fix versions do not
  resolve (newer CVEs). Tests must assert on specific ids, not on "after is empty".

Regenerate with \`scripts/regen_scanner_fixtures.sh\` (requires trivy, osv-scanner, gitleaks, uv, npm).
EOF

# ---------------------------------------------------------------- install
log "writing fixtures into ${OUT}"
mkdir -p "${OUT}/trivy" "${OUT}/osv" "${OUT}/gitleaks"
for f in trivy/before_py.json trivy/after_py.json trivy/before_js.json trivy/after_js.json \
         osv/before_py.json osv/after_py.json osv/before_js.json osv/after_js.json \
         gitleaks/one_secret.json gitleaks/clean.json VERSIONS.md README.md; do
    cp "${STAGE}/${f}" "${OUT}/${f}"
done

log "advisory ids per file:"
for f in "${OUT}"/trivy/*.json "${OUT}"/osv/*.json; do
    ids="$(grep -oE '"(CVE-[0-9]{4}-[0-9]+|GHSA(-[0-9a-z]{4}){3})"' "${f}" | tr -d '"' | sort -u | tr '\n' ' ' || true)"
    echo "  ${f#"${ROOT}"/}: ${ids:-<none>}" >&2
done
log "done"
